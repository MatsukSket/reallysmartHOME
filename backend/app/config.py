"""Константы решателя.

Значения зафиксированы в проекте и не должны задаваться в коде по месту.
"""

# Ожидание подтверждения команды моделью умного дома.
CONFIRM_TIMEOUT_S = 10

# Ожидание ответа интеллектуального модуля.
ASSISTANT_TIMEOUT_S = 30

# Зона нечувствительности по параметрам.
DELTA_BY_PARAMETER = {
    "temperature": 0.5,
    "humidity": 5.0,
}

# Допустимый пропуск срабатывания расписания.
SCHEDULE_TOLERANCE_S = 5 * 60

# Данные считаются неактуальными через указанное время после получения.
STALE_AFTER_S = 5 * 60

# Длительность блокировки после ручной команды.
LOCK_TTL_S = {
    "light": 20 * 60,
    "default": 2 * 60 * 60,
}

# Срок жизни предложения помощника.
PROPOSAL_TTL_S = 5 * 60

# Срок действия приглашения.
INVITE_TTL_S = 24 * 60 * 60

# Короткий пропуск для запросов. Живёт недолго: если его перехватят,
# воспользоваться смогут ненадолго.
ACCESS_TTL_S = 30 * 60

# Долгий пропуск на устройстве. Продлевается при каждом использовании,
# поэтому у активного пользователя вход не заканчивается. Верхняя граница
# нужна только для заброшенных устройств: если приложением не пользуются
# несколько месяцев, пропуск перестаёт действовать.
REFRESH_TTL_S = 90 * 24 * 60 * 60

# Срок действия режима администратора после повторного ввода пароля.
# Ограничение защищает на случай, если устройство осталось без присмотра.
ADMIN_MODE_TTL_S = 15 * 60

# Период фоновой работы: как часто решатель сам проверяет события и
# расписания, без внешнего запроса.
WORKER_INTERVAL_S = 1.0

# Упреждение расписания целевой температуры: решатель начинает
# приводить параметр к нужному значению заранее.
SCHEDULE_LEAD_S = 20 * 60

# Минимальный заряд пылесоса для запуска уборки, %.
VACUUM_MIN_CHARGE = 20


def delta_for(parameter: str) -> float:
    """Возвращает зону нечувствительности для параметра."""
    return DELTA_BY_PARAMETER[parameter]


def lock_ttl_for(device_type: str) -> int:
    """Возвращает длительность блокировки для типа устройства."""
    return LOCK_TTL_S.get(device_type, LOCK_TTL_S["default"])